"""Core exposure timing, EXIF rational, lookup, and boot-pool routines for 30-600s M mode."""
from __future__ import annotations
from z6_thumb_emit import (
    ThumbEmitter, R0, R1, R2, R3, R4, R5, R6, R7, R8, IP, SP, LR, PC,
    COND_EQ, COND_NE, COND_CC, COND_GE, COND_LT, COND_GT, COND_LE,
)
from z6_m600_tables import (
    N_EXT, STOCK_M_COUNT, M_COUNT, IDX_30S,
    STOCK_POOL_REQ, EXT_BLOCK_OFF, EXT_TOTAL_ALLOC, POOL_START, POOL_MAX_BASE, BLOCK_TAG,
    ADDR_ROM_MTBL, ADDR_EXT_LOOKUP, ADDR_LOOKUP_TV, ADDR_LOOKUP_RAT,
    ADDR_US_TIMER, ADDR_NS_TIMER, ADDR_EXIF_RAT, ADDR_M_FALLBACK,
    ADDR_GET_BLOCK, ADDR_BOOT_ALLOC, ADDR_POOL_RESET, ADDR_GET_MTBL,
)

POOL_DESC_ADDR = 0xC1F88798
POOL_BUMP_PTR = 0xC18FD938
STOCK_MTBL_RAM = 0xC1816920
FN_POOL_ALLOC = 0x101E5BB0
FN_POOL_FREE_BYTES = 0x101E5BD6


def emit_lookup_tv() -> bytes:
    e = ThumbEmitter(ADDR_LOOKUP_TV)
    e.set_u32(R2, ADDR_EXT_LOOKUP)
    e.mov_u16(R3, N_EXT)
    e.label("loop")
    e.ldr_u32(R1, R2, 0)
    e.cmp_reg(R0, R1)
    e.j_cond(COND_EQ, "hit")
    e.add_u12(R2, R2, 12)
    e.subs_u8(R3, 1)
    e.j_cond(COND_NE, "loop")
    e.mov_u16(R0, 0)
    e.ret_lr()
    e.label("hit")
    e.ldr_u32(R0, R2, 4)
    e.ldr_u32(R1, R2, 8)
    e.ret_lr()
    return e.finish()


def emit_lookup_rational() -> bytes:
    e = ThumbEmitter(ADDR_LOOKUP_RAT)
    e.push(R4, LR)
    e.ldr_s16(R2, R0, 0)
    e.cmp_u8(R2, 0)
    e.j_cond(COND_LE, "miss")
    e.mov_u16(R4, 0x400)
    e.cmp_reg(R2, R4)
    e.j_cond(COND_GT, "miss")
    e.ldr_u32(R3, R0, 4)
    e.cmp_u8(R3, 0)
    e.j_cond(COND_GE, "miss")
    e.mov_u16(R4, 0x2800)
    e.neg_reg(R4, R4)
    e.cmp_reg(R3, R4)
    e.j_cond(COND_LT, "miss")
    e.mov_u16(R4, 24)
    e.mul32(R3, R3, R4)
    e.set_u32(R4, ADDR_EXT_LOOKUP)
    e.mov_u16(R0, N_EXT)
    e.label("loop")
    e.ldr_u32(R1, R4, 0)
    e.mul32(R1, R1, R2)
    e.cmp_reg(R1, R3)
    e.j_cond(COND_EQ, "hit")
    e.add_u12(R4, R4, 12)
    e.subs_u8(R0, 1)
    e.j_cond(COND_NE, "loop")
    e.label("miss")
    e.mov_u16(R0, 0)
    e.pop(R4, PC)
    e.label("hit")
    e.ldr_u32(R1, R4, 4)
    e.ldr_u32(R0, R4, 8)
    e.pop(R4, PC)
    return e.finish()


def _emit_scaled_timer(addr: int, scale: int, cont_addr: int) -> bytes:
    e = ThumbEmitter(addr)
    e.push(R2, R3, R4, R5, LR)
    e.sp_sub(4)
    e.mov_reg(R4, R0)
    e.mov_reg(R5, R1)
    e.call_abs(ADDR_LOOKUP_RAT)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_EQ, "orig")
    e.set_u32(R1, scale)
    e.umull64(R0, R1, R0, R1)
    e.sp_add(4)
    e.pop(R2, R3, R4, R5, PC)
    e.label("orig")
    e.mov_reg(R0, R4)
    e.mov_reg(R1, R5)
    e.sp_add(4)
    e.pop(R2, R3, R4, R5, LR)
    e.push(R2, R3, R4, LR)
    e.ldrd_u32(R1, R0, R0, 0)
    e.jump_abs(cont_addr)
    return e.finish()


def emit_exif_rational() -> bytes:
    e = ThumbEmitter(ADDR_EXIF_RAT)
    e.push(R2, R3, R4, R5, LR)
    e.sp_sub(4)
    e.mov_reg(R4, R0)
    e.mov_reg(R5, R1)
    e.call_abs(ADDR_LOOKUP_RAT)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_EQ, "orig")
    e.mov_u16(R2, 10)
    e.mul32(R0, R0, R2)
    e.strd_u32(R0, R2, R5, 0)
    e.sp_add(4)
    e.pop(R2, R3, R4, R5, PC)
    e.label("orig")
    e.mov_reg(R0, R4)
    e.mov_reg(R1, R5)
    e.sp_add(4)
    e.pop(R2, R3, R4, R5, LR)
    e.push(R2, R3, R4, LR)
    e.set_u32(R2, 0xC1808004)
    e.mov_reg(R4, R1)
    e.jump_abs(0x101C4796)
    return e.finish()


def emit_m_index_fallback() -> bytes:
    e = ThumbEmitter(ADDR_M_FALLBACK)
    e.push(R1, R2, R3, IP)
    e.save_flags(R3)
    e.push(R3, LR)
    e.set_max_i32(R1)
    e.cmp_reg(R0, R1)
    e.j_cond(COND_NE, "done")
    e.ldr_u32(R1, SP, 0x18 + 0x1F8)
    e.cmp_u8(R1, 0)
    e.j_cond(COND_NE, "done")
    e.ldr_u32(R0, SP, 0x18 + 0x1FC)
    e.call_abs(ADDR_LOOKUP_TV)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_NE, "matched_ext")
    e.set_max_i32(R0)
    e.j_local("done")
    e.label("matched_ext")
    e.ldr_u32(R1, SP, 0x18 + 0x1F0)
    e.cmp_u8(R1, STOCK_M_COUNT)
    e.j_cond(COND_NE, "chk_ext_tbl")
    e.mov_u16(R0, 3)
    e.j_local("done")
    e.label("chk_ext_tbl")
    e.cmp_u8(R1, M_COUNT)
    e.j_cond(COND_NE, "restore_sentinel")
    e.mov_u16(R0, IDX_30S)
    e.j_local("done")
    e.label("restore_sentinel")
    e.set_max_i32(R0)
    e.label("done")
    e.pop(R3, LR)
    e.restore_flags(R3)
    e.pop(R1, R2, R3, IP)
    e.str_u32(R0, R5, 0)
    e.add_lsl(R0, R4, R0, 4)
    e.jump_abs(0x1012ED94)
    return e.finish()


def emit_get_block() -> bytes:
    e = ThumbEmitter(ADDR_GET_BLOCK)
    e.set_u32(R1, POOL_DESC_ADDR)
    e.ldr_u32(R0, R1, 0)
    e.ldr_u32(R2, R1, 4)
    e.set_u32(R1, STOCK_POOL_REQ)
    e.cmp_reg(R2, R1)
    e.j_cond(COND_NE, "invalid")
    e.set_u32(R1, POOL_START)
    e.cmp_reg(R0, R1)
    e.j_cond(COND_CC, "invalid")
    e.set_u32(R1, POOL_MAX_BASE)
    e.cmp_reg(R1, R0)
    e.j_cond(COND_CC, "invalid")
    e.tst_u8(R0, 0x3F)
    e.j_cond(COND_NE, "invalid")
    e.set_u32(R1, EXT_TOTAL_ALLOC)
    e.add_lsl(R1, R0, R1, 0)
    e.set_u32(R2, POOL_BUMP_PTR)
    e.ldr_u32(R2, R2, 0)
    e.cmp_reg(R2, R1)
    e.j_cond(COND_CC, "invalid")
    e.set_u32(R1, EXT_BLOCK_OFF)
    e.add_lsl(R0, R0, R1, 0)
    e.ldr_u32(R1, R0, 0)
    e.set_u32(R2, BLOCK_TAG)
    e.cmp_reg(R1, R2)
    e.j_cond(COND_NE, "invalid")
    e.ldr_u32(R1, R0, 4)
    e.cmp_u8(R1, M_COUNT)
    e.j_cond(COND_NE, "invalid")
    e.ldr_u32(R1, R0, 8)
    e.cmp_u8(R1, 1)
    e.j_cond(COND_NE, "invalid")
    e.barrier_sy()
    e.ret_lr()
    e.label("invalid")
    e.mov_u16(R0, 0)
    e.ret_lr()
    return e.finish()


def emit_boot_pool_alloc() -> bytes:
    e = ThumbEmitter(ADDR_BOOT_ALLOC)
    e.push(R4, R5, R6, R7, R8, LR)
    e.mov_reg(R8, R0)
    e.set_u32(R1, STOCK_POOL_REQ)
    e.cmp_reg(R8, R1)
    e.j_cond(COND_NE, "fallback")
    e.call_abs(FN_POOL_FREE_BYTES)
    e.set_u32(R1, EXT_TOTAL_ALLOC)
    e.cmp_reg(R0, R1)
    e.j_cond(COND_CC, "fallback")
    e.mov_reg(R0, R1)
    e.call_abs(FN_POOL_ALLOC)
    e.mov_reg(R4, R0)
    e.set_u32(R1, POOL_START)
    e.cmp_reg(R4, R1)
    e.j_cond(COND_CC, "ret_base")
    e.set_u32(R1, POOL_MAX_BASE)
    e.cmp_reg(R1, R4)
    e.j_cond(COND_CC, "ret_base")
    e.tst_u8(R4, 0x3F)
    e.j_cond(COND_NE, "ret_base")
    e.set_u32(R1, EXT_TOTAL_ALLOC)
    e.add_lsl(R1, R4, R1, 0)
    e.set_u32(R2, POOL_BUMP_PTR)
    e.ldr_u32(R2, R2, 0)
    e.cmp_reg(R2, R1)
    e.j_cond(COND_CC, "ret_base")
    e.set_u32(R5, EXT_BLOCK_OFF)
    e.add_lsl(R5, R4, R5, 0)
    e.mov_reg(R0, R5)
    e.mov_u16(R1, 0)
    e.mov_u16(R2, 0x210)
    e.label("zero_loop")
    e.str_post4(R1, R0)
    e.subs_u8(R2, 1)
    e.j_cond(COND_NE, "zero_loop")
    e.add_u12(R0, R5, 0x40)
    e.set_u32(R1, ADDR_ROM_MTBL)
    e.mov_u16(R2, M_COUNT * 4)
    e.label("copy_loop")
    e.ldr_post4(R3, R1)
    e.str_post4(R3, R0)
    e.subs_u8(R2, 1)
    e.j_cond(COND_NE, "copy_loop")
    e.set_u32(R0, BLOCK_TAG)
    e.str_u32(R0, R5, 0)
    e.mov_u16(R0, M_COUNT)
    e.str_u32(R0, R5, 4)
    e.barrier_sy()
    e.mov_u16(R0, 1)
    e.str_u32(R0, R5, 8)
    e.barrier_sy()
    e.label("ret_base")
    e.mov_reg(R0, R4)
    e.pop(R4, R5, R6, R7, R8, PC)
    e.label("fallback")
    e.mov_reg(R0, R8)
    e.pop(R4, R5, R6, R7, R8, LR)
    e.jump_abs(FN_POOL_ALLOC)
    return e.finish()


def emit_pool_reset() -> bytes:
    e = ThumbEmitter(ADDR_POOL_RESET)
    e.push(R0, R1, R2, R3, IP, LR)
    e.save_flags(R3)
    e.push(R3, R4)
    e.call_abs(ADDR_GET_BLOCK)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_EQ, "done")
    e.mov_u16(R2, 0)
    e.str_u32(R2, R0, 8)
    e.barrier_sy()
    e.label("done")
    e.pop(R3, R4)
    e.restore_flags(R3)
    e.pop(R0, R1, R2, R3, IP, LR)
    e.str_u32(R0, R1, 0)
    e.pop(R4, LR)
    e.jump_abs(0x101E59BC)
    return e.finish()


def emit_get_mtbl() -> bytes:
    e = ThumbEmitter(ADDR_GET_MTBL)
    e.push(R4, LR)
    e.mov_reg(R4, R0)
    e.call_abs(ADDR_GET_BLOCK)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_EQ, "stock")
    e.add_u12(R0, R0, 0x40)
    e.cmp_u8(R4, 0)
    e.j_cond(COND_EQ, "ret_ext")
    e.mov_u16(R1, M_COUNT)
    e.str_u32(R1, R4, 0)
    e.label("ret_ext")
    e.pop(R4, PC)
    e.label("stock")
    e.cmp_u8(R4, 0)
    e.j_cond(COND_EQ, "ret_stock")
    e.mov_u16(R1, STOCK_M_COUNT)
    e.str_u32(R1, R4, 0)
    e.label("ret_stock")
    e.set_u32(R0, STOCK_MTBL_RAM)
    e.pop(R4, PC)
    return e.finish()


def build_core_routines() -> list[tuple[int, str, bytes, str]]:
    return [
        (ADDR_POOL_RESET, "m600_pool_runtime", emit_pool_reset(), "Invalidate extended M-table block before pool reset"),
        (ADDR_GET_MTBL, "m600_pool_runtime", emit_get_mtbl(), "Return 120-entry M-table when ready else stock 112-entry table"),
        (ADDR_GET_BLOCK, "m600_pool_runtime", emit_get_block(), "Validate boot-pool descriptor, bounds, alignment, and ready flag"),
        (ADDR_BOOT_ALLOC, "m600_pool_runtime", emit_boot_pool_alloc(), "Allocate 0x75D80 pool block and populate 120-entry M-table"),
        (ADDR_LOOKUP_TV, "m600_timing_exif", emit_lookup_tv(), "Pure-ROM lookup from signed Tv*24 to (ui_id, seconds)"),
        (ADDR_LOOKUP_RAT, "m600_timing_exif", emit_lookup_rational(), "Pure-ROM rational exposure lookup returning (seconds, ui_id)"),
        (ADDR_US_TIMER, "m600_timing_exif", _emit_scaled_timer(ADDR_US_TIMER, 1_000_000, 0x101C4874), "Microsecond exposure duration for 60s..600s"),
        (ADDR_NS_TIMER, "m600_timing_exif", _emit_scaled_timer(ADDR_NS_TIMER, 1_000_000_000, 0x1011C150), "Nanosecond exposure duration for 60s..600s"),
        (ADDR_EXIF_RAT, "m600_timing_exif", emit_exif_rational(), "EXIF ExposureTime rational {seconds*10, 10} for 60s..600s"),
        (ADDR_M_FALLBACK, "m600_pool_runtime", emit_m_index_fallback(), "Clamp sentinel M-table index to 30s entry (3 or 11)"),
    ]
