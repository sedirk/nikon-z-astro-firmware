"""Dial stepping, allowed-Tv list filtering, and min-Tv clamp routines for 30-600s M mode."""
from __future__ import annotations
from z6_thumb_emit import (
    ThumbEmitter, R0, R1, R2, R3, R4, R5, R6, R7, R8, R9, R10, IP, SP, LR, PC,
    COND_EQ, COND_NE, COND_CS, COND_CC, COND_GE,
)
from z6_m600_tables import (
    N_EXT, M_COUNT, IDX_600S, IDX_60S, IDX_30S,
    ADDR_DIAL_PREREF, ADDR_MTBL_REF, ADDR_ALLOWED_TV,
    ADDR_ACTIVE_UI, ADDR_DIAL_STEP, ADDR_DIAL_BURST, ADDR_MIN_TV8, ADDR_LOOKUP_TV,
)


def emit_dial_prerefresh() -> bytes:
    e = ThumbEmitter(ADDR_DIAL_PREREF)
    e.mov_u16(R0, 0)
    e.mov_u16(R1, 0)
    e.call_abs(0x1012EC70)
    e.mov_reg(R0, R10)
    e.call_abs(0x101308C2)
    e.jump_abs(0x1012A69A)
    return e.finish()


def emit_mtbl_refresh() -> bytes:
    e = ThumbEmitter(ADDR_MTBL_REF)
    e.mov_u16(R0, 0)
    e.mov_u16(R1, 0)
    e.call_abs(0x1012EC70)
    e.mov_u16(R0, 0)
    e.call_abs(0x10090102)
    e.jump_abs(0x1012A78A)
    return e.finish()


def emit_allowed_tv_filter() -> bytes:
    e = ThumbEmitter(ADDR_ALLOWED_TV)
    e.cmp_u8(R6, N_EXT)
    e.j_cond(COND_CS, "std_entry")
    e.cmp_u8(R3, 0)
    e.j_cond(COND_NE, "skip_ext")
    e.ldr_u32(R7, SP, 0x98)
    e.ldr_u8(R5, R7, 0xA4)
    e.cmp_u8(R5, 0)
    e.j_cond(COND_NE, "skip_ext")
    e.ldr_u32(R5, R7, 0xB8)
    e.cmp_u8(R5, 3)
    e.j_cond(COND_NE, "skip_ext")
    e.ldr_u32(R5, R1, 0x0C)
    e.ldr_u32_idx(R7, R8, R6, 3)
    e.str_u32_idx(R7, R4, R5, 2)
    e.add_u12(R5, R5, 1)
    e.str_u32(R5, R1, 0x0C)
    e.label("skip_ext")
    e.jump_abs(0x101509A6)
    e.label("std_entry")
    e.add_lsl(R5, R8, R6, 3)
    e.jump_abs(0x10150942)
    return e.finish()


def emit_dial_single_step() -> bytes:
    e = ThumbEmitter(ADDR_DIAL_STEP)
    e.push(R1, R2)
    e.ldr_u32(R1, SP, 0x1C)
    e.cmp_u8(R1, M_COUNT)
    e.j_cond(COND_NE, "done")
    e.ldr_u32(R1, R6, 0x3C)
    e.cmp_u8(R1, 0)
    e.j_cond(COND_EQ, "done")
    e.cmp_u8(R8, IDX_30S)
    e.j_cond(COND_EQ, "at_30s")
    e.j_cond(COND_CS, "above_30s")
    e.cmp_u8(R8, IDX_600S)
    e.j_cond(COND_CC, "below_600s")
    e.cmp_reg(R0, R8)
    e.j_cond(COND_EQ, "done")
    e.j_cond(COND_CC, "step_slower")
    e.add_u12(R0, R8, 1)
    e.j_local("done")
    e.label("step_slower")
    e.sub_u12(R0, R8, 1)
    e.j_local("done")
    e.label("below_600s")
    e.cmp_u8(R0, IDX_600S)
    e.j_cond(COND_CC, "done")
    e.mov_u16(R0, IDX_600S)
    e.j_local("done")
    e.label("at_30s")
    e.cmp_u8(R0, IDX_30S)
    e.j_cond(COND_CS, "done")
    e.mov_u16(R0, IDX_60S)
    e.j_local("done")
    e.label("above_30s")
    e.cmp_u8(R0, IDX_30S)
    e.j_cond(COND_CS, "done")
    e.mov_u16(R0, IDX_30S)
    e.label("done")
    e.pop(R1, R2)
    e.cmp_u8(R9, 0)
    e.j_cond(COND_NE, "sb_nonzero")
    e.jump_abs(0x1012A6D2)
    e.label("sb_nonzero")
    e.jump_abs(0x1012A6E2)
    return e.finish()


def emit_dial_multiclick_stop() -> bytes:
    e = ThumbEmitter(ADDR_DIAL_BURST)
    e.cmp_u8(R7, 0)
    e.j_cond(COND_NE, "plain")
    e.push(R0, R1, R7, LR)
    e.sp_sub(8)
    e.mov_reg(R0, SP)
    e.call_abs(0x10090102)
    e.ldr_u32(R1, SP, 0)
    e.cmp_u8(R1, M_COUNT)
    e.j_cond(COND_NE, "pop_plain")
    e.ldr_u32(R1, R0, 0x3C)
    e.cmp_u8(R1, 0)
    e.j_cond(COND_EQ, "pop_plain")
    e.sp_add(8)
    e.mov_u16(R0, 0x204)
    e.call_abs(0x1015BEBE)
    e.sxth(R7, R0)
    e.pop(R0, R1)
    e.call_abs(0x1012A68C)
    e.mov_reg(R0, R7)
    e.call_abs(ADDR_LOOKUP_TV)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_NE, "cont")
    e.mov_u16(R0, 0x204)
    e.call_abs(0x1015BEBE)
    e.sxth(R0, R0)
    e.push(R0, R1)
    e.call_abs(ADDR_LOOKUP_TV)
    e.mov_reg(R2, R0)
    e.pop(R0, R1)
    e.cmp_u8(R2, 0)
    e.j_cond(COND_NE, "stop")
    e.mov_u16(R1, 120)
    e.neg_reg(R1, R1)
    e.cmp_reg(R0, R1)
    e.j_cond(COND_NE, "cont")
    e.cmp_reg(R7, R1)
    e.j_cond(COND_EQ, "cont")
    e.label("stop")
    e.pop(R7, LR)
    e.jump_abs(0x1012A880)
    e.label("cont")
    e.pop(R7, LR)
    e.jump_abs(0x1012A878)
    e.label("pop_plain")
    e.sp_add(8)
    e.pop(R0, R1, R7, LR)
    e.label("plain")
    e.call_abs(0x1012A68C)
    e.jump_abs(0x1012A878)
    return e.finish()


def emit_min_tv8_clamp() -> bytes:
    e = ThumbEmitter(ADDR_MIN_TV8)
    e.push(R0, R1, R2, R3, IP, LR)
    e.save_flags(R0)
    e.push(R0, R1)
    e.set_u32(R0, 0xC24CD9C0)
    e.ldr_s16(R0, R0, 0)
    e.lsl_imm(R0, R0, 3)
    e.cmp_reg(R7, R0)
    e.j_cond(COND_NE, "done")
    e.mov_u16(R1, 0x3C0)
    e.neg_reg(R1, R1)
    e.cmp_reg(R5, R1)
    e.j_cond(COND_NE, "done")
    e.ldr_u8(R0, R6, 0)
    e.cmp_u8(R0, 3)
    e.j_cond(COND_NE, "done")
    e.call_abs(ADDR_ACTIVE_UI)
    e.cmp_u8(R0, 0)
    e.j_cond(COND_EQ, "done")
    e.mov_reg(R5, R7)
    e.label("done")
    e.pop(R0, R1)
    e.restore_flags(R0)
    e.pop(R0, R1, R2, R3, IP, LR)
    e.cmp_reg(R7, R5)
    e.j_cond(COND_GE, "skip_clamp")
    e.jump_abs(0x100DAD6A)
    e.label("skip_clamp")
    e.jump_abs(0x100DAD6C)
    return e.finish()


def build_dial_routines() -> list[tuple[int, str, bytes, str]]:
    return [
        (ADDR_DIAL_PREREF, "m600_dial_control", emit_dial_prerefresh(), "Refresh M-mode step enable flags prior to dial step"),
        (ADDR_MTBL_REF, "m600_dial_control", emit_mtbl_refresh(), "Refresh M-mode step enable flags prior to M-table query"),
        (ADDR_ALLOWED_TV, "m600_dial_control", emit_allowed_tv_filter(), "Include 60s..600s in allowed-Tv list strictly in M still mode"),
        (ADDR_DIAL_STEP, "m600_dial_control", emit_dial_single_step(), "Single-step command dial transitions across Bulb..600s..60s..30s"),
        (ADDR_DIAL_BURST, "m600_dial_control", emit_dial_multiclick_stop(), "Stop multi-click dial burst cleanly at 30s and 60s boundaries"),
        (ADDR_MIN_TV8, "m600_dial_control", emit_min_tv8_clamp(), "Allow Tv*8 below -960 (30s) when an extended M-still speed is active"),
    ]
